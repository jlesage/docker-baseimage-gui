#!/bin/sh
#
# Helper script that builds yad as a static binary.
#
# NOTE: This script is expected to be run under Alpine Linux.
#

set -e # Exit immediately if a command exits with a non-zero status.
set -u # Treat unset variables as an error.

# Define software versions.
YAD_VERSION=0.42.90

# Use the same versions has Alpine 3.20.
PANGO_VERSION=1.52.2
GTK_VERSION=3.24.43
ATK_VERSION=2.38.0
GDKPIXBUF_VERSION=2.42.11
CAIRON_VERSION=1.18.0
PIXMAN_VERSION=0.43.4
BROTLI_VERSION=1.1.0
LIBEPOXY_VERSION=1.5.10
LIBXRANDR_VERSION=1.5.4

# Define software download URLs.
YAD_URL=https://github.com/step-/yad/archive/refs/tags/${YAD_VERSION}.tar.gz
PANGO_URL=https://download.gnome.org/sources/pango/${PANGO_VERSION%.*}/pango-${PANGO_VERSION}.tar.xz
GTK_URL=https://download.gnome.org/sources/gtk+/${GTK_VERSION%.*}/gtk%2B-${GTK_VERSION}.tar.xz
ATK_URL=https://download.gnome.org/sources/atk/${ATK_VERSION%.*}/atk-${ATK_VERSION}.tar.xz
GDKPIXBUF_URL=https://download.gnome.org/sources/gdk-pixbuf/${GDKPIXBUF_VERSION%.*}/gdk-pixbuf-${GDKPIXBUF_VERSION}.tar.xz
CAIRO_URL=https://gitlab.freedesktop.org/cairo/cairo/-/archive/${CAIRON_VERSION}/cairo-${CAIRON_VERSION}.tar.bz2
PIXMAN_URL=https://www.x.org/releases/individual/lib/pixman-${PIXMAN_VERSION}.tar.xz
BROTLI_URL=https://github.com/google/brotli/archive/refs/tags/v${BROTLI_VERSION}.tar.gz
LIBEPOXY_URL=https://github.com/anholt/libepoxy/archive/refs/tags/${LIBEPOXY_VERSION}.tar.gz
LIBXRANDR_URL=https://www.x.org/releases/individual/lib/libXrandr-${LIBXRANDR_VERSION}.tar.xz

# Same baseline as abuild, plus flags that shrink the static binary.
# -Oz is smaller than -Os. Function sections let the final link drop unused
# code. Thin LTO does the same across compilation units. Unwind tables are
# omitted; nothing in this binary throws exceptions.
export CFLAGS="-Oz -fomit-frame-pointer -Wno-expansion-to-defined -ffunction-sections -fdata-sections -fno-unwind-tables -fno-asynchronous-unwind-tables -flto=thin -DG_DISABLE_CAST_CHECKS"
export CXXFLAGS="$CFLAGS"
export CPPFLAGS="$CFLAGS"
export LDFLAGS="-fuse-ld=lld -flto=thin -Wl,--as-needed,-O1,--sort-common"

export CC=xx-clang
export CXX=xx-clang++

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

log() {
    echo ">>> $*"
}

#
# Install required packages.
#
HOST_PKGS="\
    curl \
    build-base \
    abuild \
    clang \
    lld \
    cmake \
    meson \
    autoconf \
    automake \
    intltool \
    pkgconfig \
    glib-dev \
    gtk-update-icon-cache \
    gettext \
"

TARGET_PKGS="\
    g++ \
    glib-dev \
    glib-static \
    util-linux-dev \
    util-linux-static \
    gettext-static \
    pcre2-dev \
    expat-static \
    libffi-dev \
    zlib-static \
    bzip2-static \
    graphite2-static \
    libpng-static \
    libx11-static \
    libxcb-static \
    libxdmcp-dev \
    libxau-dev \
    libxrender-dev \
    fribidi-dev \
    fribidi-static \
    harfbuzz-dev \
    harfbuzz-static \
    freetype-static \
    libxext-static \
    libxfixes-dev \
    libxi-dev \
    libxi-static \
    libeconf-dev \
    mesa-dev \
"

log "Installing required Alpine packages..."
apk --no-cache add $HOST_PKGS
xx-apk --no-cache --no-scripts add $TARGET_PKGS

echo "[binaries]
pkgconfig = '$(xx-info)-pkg-config'

[properties]
sys_root = '$(xx-info sysroot)'
pkg_config_libdir = '$(xx-info sysroot)/usr/lib/pkgconfig'

[host_machine]
system = 'linux'
cpu_family = '$(xx-info arch)'
cpu = '$(xx-info arch)'
endian = 'little'
" > /tmp/meson-cross.txt

#
# Build pango
# The static library is not provided by Alpine repository, so we need to build
# it ourself.
#
mkdir /tmp/pango
log "Downloading pango..."
curl -# -L -f ${PANGO_URL} | tar -xJ --strip 1 -C /tmp/pango
log "Configuring pango..."
(
    cd /tmp/pango && abuild-meson \
        -Ddefault_library=static \
        -Dintrospection=disabled \
        -Dgtk_doc=false \
        --cross-file /tmp/meson-cross.txt \
        build \
)
log "Compiling pango..."
meson compile -C /tmp/pango/build
log "Installing pango..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/pango/build

#
# Build fontconfig.
#
# Fontconfig is already built by an earlier stage in Dockerfile.  The static
# library will be used by JWM.  We need to compile our own version to adjust
# different paths used by fontconfig.
# Note that the fontconfig cache generated by fc-cache is architecture
# dependent.  Thus, we won't generate one, but it's not a problem since
# we have very few fonts installed.
#

log "Installing fontconfig..."
cp -av /tmp/fontconfig-install/usr $(xx-info sysroot)

#
# Build atk.
# The static library is not provided by Alpine repository, so we need to build
# it ourself.
#
mkdir /tmp/atk
log "Downloading atk..."
curl -# -L -f ${ATK_URL} | tar -xJ --strip 1 -C /tmp/atk
log "Configuring atk..."
(
    cd /tmp/atk && abuild-meson \
        -Ddefault_library=static \
        -Dintrospection=false \
        -Ddocs=false \
        --cross-file /tmp/meson-cross.txt \
        build \
)
log "Compiling atk..."
meson compile -C /tmp/atk/build
log "Installing atk..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/atk/build

#
# Build GdkPixbuf.
# The static library is not provided by Alpine repository, so we need to build
# it ourself.
#
mkdir /tmp/gdkpixbuf
log "Downloading GdkPixbuf..."
curl -# -L -f ${GDKPIXBUF_URL} | tar -xJ --strip 1 -C /tmp/gdkpixbuf
log "Configuring GdkPixbuf..."
(
    cd /tmp/gdkpixbuf && abuild-meson \
        -Ddefault_library=both \
        -Dpng=enabled \
        -Dtiff=disabled \
        -Djpeg=disabled \
        -Dgif=disabled \
        -Dbuiltin_loaders=png \
        -Dgtk_doc=false \
        -Ddocs=false \
        -Dtests=false \
        -Dintrospection=disabled \
        -Dman=false \
        -Drelocatable=false \
        -Dnative_windows_loaders=false \
        -Dinstalled_tests=false \
        -Dgio_sniffing=false \
        --cross-file /tmp/meson-cross.txt \
        build \
)
log "Compiling GdkPixbuf..."
meson compile -C /tmp/gdkpixbuf/build
log "Installing GdkPixbuf..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/gdkpixbuf/build

#
# Build libXrandr.
# The static library is not provided by Alpine repository, so we need to build
# it ourself.
#
mkdir /tmp/libxrandr
log "Downloading libXrandr..."
curl -# -L -f ${LIBXRANDR_URL} | tar -xJ --strip 1 -C /tmp/libxrandr
log "Configuring libXrandr..."
# Keep this small autotools build off LTO. Libtool drops -flto from the link.
(
    cd /tmp/libxrandr && \
    CFLAGS="-Os -fomit-frame-pointer -Wno-expansion-to-defined" \
    LDFLAGS= \
    ./configure \
        --build=$(TARGETPLATFORM= xx-clang --print-target-triple) \
        --host=$(xx-clang --print-target-triple) \
        --prefix=/usr \
        --disable-shared \
        --enable-static \
        --enable-malloc0returnsnull \
)
log "Compiling libXrandr..."
make -C /tmp/libxrandr -j$(nproc)
log "Installing libXrandr..."
make DESTDIR=$(xx-info sysroot) -C /tmp/libxrandr install
find $(xx-info sysroot)usr/lib -name "*.la" -delete

# mesa-dev installs xdamage.pc, but Alpine has no static libXdamage and YAD
# does not need the extension. Hide it so GTK does not link XDamage.
rm -f "$(xx-info sysroot)usr/lib/pkgconfig/xdamage.pc"

#
# Build libepoxy.
# The static library is not provided by Alpine repository, so we need to build
# it ourself.
#
mkdir /tmp/libepoxy
log "Downloading libepoxy..."
curl -# -L -f ${LIBEPOXY_URL} | tar -xz --strip 1 -C /tmp/libepoxy
log "Configuring libepoxy..."
(
    cd /tmp/libepoxy && abuild-meson \
        -Ddefault_library=static \
        -Ddocs=false \
        -Dtests=false \
        -Dglx=yes \
        -Degl=no \
        --cross-file /tmp/meson-cross.txt \
        build \
)
log "Compiling libepoxy..."
meson compile -C /tmp/libepoxy/build
log "Installing libepoxy..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/libepoxy/build

#
# Build GTK.
# The static library is not provided by Alpine repository, so we need to build
# it ourself.
#
mkdir /tmp/gtk
log "Downloading GTK..."
curl -# -L -f ${GTK_URL} | tar -xJ --strip 1 -C /tmp/gtk
log "Patching GTK..."
patch -p1 -d /tmp/gtk < "$SCRIPT_DIR"/disable-atk-bridge.patch
log "Configuring GTK..."
(
    cd /tmp/gtk && abuild-meson \
        -Ddefault_library=static \
        -Dx11_backend=true \
        -Dwayland_backend=false \
        -Dxinerama=no \
        -Dcolord=no \
        -Dgtk_doc=false \
        -Dman=false \
        -Dintrospection=false \
        -Ddemos=false \
        -Dexamples=false \
        -Dtests=false \
        -Dprint_backends=file \
        -Dbuiltin_immodules=backend \
        -Datk_bridge=false \
        --cross-file /tmp/meson-cross.txt \
        build \
)
log "Compiling GTK..."
meson compile -C /tmp/gtk/build
log "Installing GTK..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/gtk/build

#
# Build cairo.
# The library in Alpine repository is built with LTO, which causes static
# linking issue, so we need to build it ourself.
#
mkdir /tmp/cairo
log "Downloading cairo..."
curl -# -L -f ${CAIRO_URL} | tar -xj --strip 1 -C /tmp/cairo
log "Patching cairo..."
patch -p1 -d /tmp/cairo < "$SCRIPT_DIR"/cairo-meson-fix.patch
log "Configuring cairo..."
(
    cd /tmp/cairo && abuild-meson \
        -Ddefault_library=both \
        -Dtests="disabled" \
        -Dgtk_doc=false \
        -Dxcb=disabled \
        -Dxlib-xcb=disabled \
        -Dtee=disabled \
        -Dspectre=disabled \
        -Dsymbol-lookup=disabled \
        --cross-file /tmp/meson-cross.txt \
        build \
)
log "Compiling cairo..."
meson compile -C /tmp/cairo/build
log "Installing cairo..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/cairo/build

#
# Build pixman.
# The library in Alpine repository is built with LTO, which causes static
# linking issue, so we need to build it ourself.
#
mkdir /tmp/pixman
log "Downloading pixman..."
curl -# -L -f ${PIXMAN_URL} | tar -xJ --strip 1 -C /tmp/pixman
log "Patching pixman..."
patch -p1 -d /tmp/pixman < "$SCRIPT_DIR"/pixman-clang-arm-asm.patch
log "Configuring pixman..."
(
    cd /tmp/pixman && \
    LDFLAGS="$LDFLAGS -Wl,-z,stack-size=2097152" \
    abuild-meson \
        -Db_lto=false \
        -Ddefault_library=static \
        -Dtests=disabled \
        -Ddemos=disabled \
        --cross-file /tmp/meson-cross.txt \
        . build
)
log "Compiling pixman..."
meson compile -C /tmp/pixman/build
log "Installing pixman..."
DESTDIR=$(xx-info sysroot) meson install --no-rebuild -C /tmp/pixman/build

#
# Build brotli.
# The library in Alpine repository is built with LTO, which causes static
# linking issue, so we need to build it ourself.
#
mkdir /tmp/brotli
log "Downloading brotli..."
curl -# -L -f ${BROTLI_URL} | tar -xz --strip 1 -C /tmp/brotli
log "Configuring brotli..."
(
    mkdir /tmp/brotli/build && \
    cd /tmp/brotli/build && cmake \
        $(xx-clang --print-cmake-defines) \
        -DCMAKE_FIND_ROOT_PATH=$(xx-info sysroot) \
        -DCMAKE_FIND_ROOT_PATH_MODE_LIBRARY=ONLY \
        -DCMAKE_FIND_ROOT_PATH_MODE_INCLUDE=ONLY \
        -DCMAKE_FIND_ROOT_PATH_MODE_PACKAGE=ONLY \
        -DCMAKE_FIND_ROOT_PATH_MODE_PROGRAM=NEVER \
        -DCMAKE_INSTALL_PREFIX=/usr \
        -DCMAKE_BUILD_TYPE=None \
	-DBUILD_SHARED_LIBS=OFF \
        ..
)
log "Compiling brotli..."
make -C /tmp/brotli/build -j$(nproc)
log "Installing brotli..."
make DESTDIR=$(xx-info sysroot) -C /tmp/brotli/build install

#
# Build YAD.
#
mkdir /tmp/yad
log "Downloading YAD..."
curl -# -L -f ${YAD_URL} | tar xz --strip 1 -C /tmp/yad
log "Patching YAD..."
patch -p1 -d /tmp/yad < "$SCRIPT_DIR"/show-button-images.patch
log "Configuring YAD..."
export LDFLAGS="$LDFLAGS --static -static -Wl,--strip-all,--gc-sections,--icf=safe" && \
(
    cd /tmp/yad && \
    autoreconf -ivf && \
    intltoolize && \
    LIBS="-lX11 -lxcb -lXdmcp -lXau -lpcre2-8 -lpixman-1 -lffi -lpng -lz -lbz2 -lgraphite2 -lexpat -lXrender -luuid -lbrotlidec -lbrotlicommon -lmount -lblkid -lfreetype -leconf -lgmodule-2.0 -lepoxy -lXi -lXrandr -lXfixes -lXext -lcairo-gobject" \
    ./configure \
        --build=$(TARGETPLATFORM= xx-clang --print-target-triple) \
        --host=$(xx-clang --print-target-triple) \
        --prefix=/usr \
        --with-gtk=gtk3 \
        --disable-spell \
        --disable-sourceview \
        --disable-gio \
        --disable-icon-browser \
        --disable-html \
        --disable-tools \
)
log "Compiling YAD..."
make -C /tmp/yad -j$(nproc)
log "Installing YAD..."
make DESTDIR=/tmp/yad-install -C /tmp/yad install

#
# Cleanup.
#
log "Performing cleanup..."
apk --no-cache del $HOST_PKGS
xx-apk --no-cache --no-scripts del $TARGET_PKGS
apk --no-cache add util-linux # Linux tools still needed and they might be removed if pulled by dependencies.
rm -rf /tmp/yad
